// 重新生成 src/websearch/vendor/turndown.bundle.js。
//
// 背景（2026-09-02 Phase 16 真实链路验证实测发现）：Claude Code 自身是 `bun build --compile`
// 编译出的单文件可执行程序（`claude.exe`），其内嵌的 Bun 运行时对通过 `--preload` 注入的
// 外部脚本，只支持相对/绝对路径的文件 import，**不支持任何 bare specifier 的 npm 包解析**
// （不管有没有 node_modules、不管 NODE_PATH、不管 cwd）——`import "turndown"` 这类写法在
// 编译进真实 claude 进程时会直接报 "Cannot find package"。这不是 node_modules 缺失的问题，
// 是编译产物本身的运行时限制。
//
// 解决方式：用 `bun build` 把 turndown（及其唯一传递依赖 @mixmark-io/domino）连同它们内部
// 互相的 require/import 全部内联打包成一个不含任何 bare specifier 的单文件，提交进仓库；
// enrich.ts 用相对路径 import 这个 bundle，而不是 `import "turndown"`。这个 bundle 只在
// turndown/@mixmark-io/domino 版本升级时需要重新生成，运行 `bun run vendor:turndown`。
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const PROJECT_ROOT = join(import.meta.dir, "..");
const OUT_PATH = join(PROJECT_ROOT, "src", "websearch", "vendor", "turndown.bundle.js");

// 临时入口文件必须落在项目目录内（而不是系统 tmp 目录）——Bun 的模块解析是从"发起 import
// 的文件所在目录"往上找 node_modules，放在项目外会找不到 turndown。
const tmpDir = mkdtempSync(join(PROJECT_ROOT, ".vendor-build-tmp-"));
const entryPath = join(tmpDir, "entry.ts");
writeFileSync(entryPath, `export { default } from "turndown";\n`);

const result = await Bun.build({
  entrypoints: [entryPath],
  target: "bun",
  format: "esm",
  minify: false,
});

if (!result.success) {
  for (const log of result.logs) console.error(log);
  rmSync(tmpDir, { recursive: true, force: true });
  process.exit(1);
}

const output = await result.outputs[0]!.text();
const header = `// AUTO-GENERATED by scripts/build-vendor.ts — do not edit by hand.
// Vendored bundle of turndown@7.2.4 (MIT) + @mixmark-io/domino@2.2.0 (BSD-2-Clause),
// inlined so this file has zero bare-specifier imports left (see script header for why).
// Regenerate with: bun run vendor:turndown
`;
writeFileSync(OUT_PATH, header + output);

// 配套的类型声明——bundle 本身是纯 .js，没有类型信息；这里借用 @types/turndown 的真实类型
// 重新导出，让 enrich.ts 里 import 这个 bundle 时仍然有完整类型检查，不需要 `allowJs`。
const dtsPath = OUT_PATH.replace(/\.js$/, ".d.ts");
writeFileSync(
  dtsPath,
  `// AUTO-GENERATED by scripts/build-vendor.ts — do not edit by hand.
import type TurndownServiceType from "turndown";
declare const TurndownService: typeof TurndownServiceType;
export default TurndownService;
`,
);

rmSync(tmpDir, { recursive: true, force: true });
console.error(`[vendor] wrote ${OUT_PATH} (${(output.length / 1024).toFixed(0)} KB) + ${dtsPath}`);
